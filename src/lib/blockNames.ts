/**
 * 方块 id 的中文显示名。
 *
 * 先查完整对照表；查不到再按「材质 + 类型」拼（`sandstone_wall` → 砂岩墙），
 * 这样楼梯、台阶、墙、地毯这些组合名不用逐个登记；最后才退回英文名，
 * 而不是显示成 `minecraft:some_mod_block` —— 至少还能读。
 */
export function blockDisplayName(block: string): string {
  const name = block.startsWith("minecraft:") ? block.slice("minecraft:".length) : block;
  const known = BLOCK_NAMES[name];
  if (known) {
    return known;
  }

  for (const [suffix, label] of TYPE_SUFFIXES) {
    if (!name.endsWith(`_${suffix}`)) {
      continue;
    }
    const material = MATERIAL_NAMES[name.slice(0, -(suffix.length + 1))];
    if (material) {
      return `${material}${label}`;
    }
  }

  // 地毯：`pink_carpet` → 粉红色地毯。
  if (name.endsWith("_carpet")) {
    const colour = MATERIAL_NAMES[name.slice(0, -"_carpet".length)];
    if (colour) {
      return `${colour}地毯`;
    }
  }

  return fallbackName(name);
}
