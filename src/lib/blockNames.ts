/** 没有收录在表里的方块，把 `cherry_planks` 变成 `Cherry Planks`。 */
function fallbackName(name: string): string {
  return name
    .split("_")
    .filter(Boolean)
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join(" ");
}

