//! Minecraft 数据版本 → 正式版名称的对照表。
//!
//! `.litematic` 头部的 `MinecraftDataVersion` 是创建该文件的游戏内部版本号。
//! 投影的方块状态（调色板字符串）在不同数据版本间可能含义不同，所以「跨版本
//! 使用」时先告诉用户文件出自哪个版本。这里只收录正式版的关键节点：查找返回
//! **不大于**给定数据版本的最新正式版，前端据此显示「出自 MC X.Y.Z 或更新」。

/// (数据版本, 正式版名称)，按数据版本升序。
const RELEASES: &[(i32, &str)] = &[
    (1343, "1.12.2"),
    (1631, "1.13.2"),
    (1976, "1.14.4"),
    (2225, "1.15.2"),
    (2586, "1.16.5"),
    (2730, "1.17.1"),
    (2975, "1.18.2"),
    (3120, "1.19.2"),
    (3337, "1.19.4"),
    (3465, "1.20.1"),
    (3700, "1.20.4"),
    (3839, "1.20.6"),
    (3953, "1.21"),
    (3955, "1.21.1"),
    (4082, "1.21.3"),
    (4189, "1.21.4"),
    (4325, "1.21.5"),
    (4435, "1.21.6"),
    (4438, "1.21.7"),
    (4440, "1.21.8"),
    (4554, "1.21.9"),
    // 26.x 起 Minecraft 换了版本号方案（`26.1.2` 这种）。这几条来自各版本
    // jar 里 `version.json` 的 `world_version`。缺了它们，新版本的文件会被
    // 就近错误地标成 1.21.8。
    (4788, "26.1.1"),
    (4790, "26.1.2"),
    (5023, "26.3"),
];

/// 返回不大于 `data_version` 的最新正式版名称；早于表中最早节点时返回 `None`。
#[must_use]
pub fn nearest_release(data_version: i32) -> Option<&'static str> {
    let position = RELEASES.partition_point(|(version, _)| *version <= data_version);
    if position == 0 {
        None
    } else {
        Some(RELEASES[position - 1].1)
    }
}

